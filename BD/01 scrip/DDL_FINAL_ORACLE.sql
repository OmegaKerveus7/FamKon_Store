CREATE TABLE USUARIO (
    ID_USUARIO          NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_SITIO            NUMBER(19),
    ID_FOTO_ORIGINAL    NUMBER(19),
    ID_FOTO_MODIFICADA  NUMBER(19),
