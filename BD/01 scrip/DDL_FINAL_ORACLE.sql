        'PEDIDO_ESTADO_HISTORIAL', 'PAGO', 'ENTREGA'
    );

    SELECT COUNT(*) INTO V_VISTAS
    FROM USER_VIEWS
    WHERE VIEW_NAME IN (
        'VW_PEDIDO_RESUMEN', 'VW_TRACKING_PEDIDO', 'VW_VENTAS_DASHBOARD'
    );

    SELECT COUNT(*) INTO V_TRIGGERS
    FROM USER_TRIGGERS
    WHERE TRIGGER_NAME IN (
        'TRG_SITIO_BU_FECHA', 'TRG_USUARIO_BU_FECHA',
        'TRG_PRODUCTO_BU_FECHA', 'TRG_CARRITO_BU_FECHA',
        'TRG_PEDIDO_BU_FECHA'
    );

    DBMS_OUTPUT.PUT_LINE('Tablas esperadas: 24 / creadas: ' || V_TABLAS);
    DBMS_OUTPUT.PUT_LINE('Vistas esperadas: 3 / creadas: ' || V_VISTAS);
    DBMS_OUTPUT.PUT_LINE('Triggers esperados: 5 / creados: ' || V_TRIGGERS);

    IF V_TABLAS <> 24 OR V_VISTAS <> 3 OR V_TRIGGERS <> 5 THEN
        RAISE_APPLICATION_ERROR(-20001, 'La validacion de objetos no coincide.');
    END IF;

    DBMS_OUTPUT.PUT_LINE('DDL BASE FINAL ejecutado correctamente.');
END;
