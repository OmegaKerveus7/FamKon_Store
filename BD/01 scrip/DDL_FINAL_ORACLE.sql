    CONSTRAINT CK_ARCHIVO_TIPO CHECK (TIPO_ARCHIVO IN (
        'FOTO_USUARIO_ORIGINAL',
        'FOTO_USUARIO_MODIFICADA',
        'IMAGEN_PRODUCTO',
        'DISENO_PERSONALIZACION',
        'EVIDENCIA_ENTREGA'
