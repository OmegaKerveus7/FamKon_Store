CREATE TABLE SITIO (
    ID_SITIO            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY,
    CODIGO              VARCHAR2(20)                         NOT NULL,
    NOMBRE              VARCHAR2(120)                        NOT NULL,
    DOMINIO             VARCHAR2(200),
    ACTIVO              CHAR(1)       DEFAULT 'S'            NOT NULL,
    FECHA_CREACION      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    FECHA_MODIFICACION  TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_SITIO PRIMARY KEY (ID_SITIO),
    CONSTRAINT UK_SITIO_CODIGO UNIQUE (CODIGO),
    CONSTRAINT CK_SITIO_ACTIVO CHECK (ACTIVO IN ('S', 'N'))
);

