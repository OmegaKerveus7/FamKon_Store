        ELSIF V_CODIGO = 'NO_ENCONTRADO' THEN
            PKG_PEDIDO.SP_CAMBIAR_ESTADO(V_PEDIDO, 'COMPRADOR_NO_ENCONTRADO', P_ID_USUARIO_ACTOR,
                COALESCE(P_OBSERVACIONES, 'Comprador no encontrado.'), NULL);
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20609, 'No existe la entrega o estado.');
