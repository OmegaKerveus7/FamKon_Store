CREATE OR REPLACE PACKAGE BODY PKG_CARRITO AS
    PROCEDURE SP_OBTENER_O_CREAR (
        P_ID_USUARIO IN CARRITO.ID_USUARIO%TYPE,
        P_ID_SITIO IN CARRITO.ID_SITIO%TYPE,
        O_ID_CARRITO OUT CARRITO.ID_CARRITO%TYPE
    ) AS
        V_EXISTE NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_EXISTE
          FROM USUARIO U JOIN SITIO S ON S.ID_SITIO = P_ID_SITIO
         WHERE U.ID_USUARIO = P_ID_USUARIO AND U.ID_SITIO = P_ID_SITIO
           AND U.ACTIVO = 'S' AND U.BLOQUEADO = 'N' AND S.ACTIVO = 'S';
        IF V_EXISTE = 0 THEN
            RAISE_APPLICATION_ERROR(-20401, 'El usuario o sitio no es valido.');
        END IF;

        BEGIN
            SELECT ID_CARRITO INTO O_ID_CARRITO
              FROM CARRITO
             WHERE ID_USUARIO = P_ID_USUARIO AND ID_SITIO = P_ID_SITIO AND ESTADO = 'ABIERTO';
        EXCEPTION
            WHEN NO_DATA_FOUND THEN
                BEGIN
                    INSERT INTO CARRITO (ID_USUARIO, ID_SITIO)
                    VALUES (P_ID_USUARIO, P_ID_SITIO)
                    RETURNING ID_CARRITO INTO O_ID_CARRITO;
                EXCEPTION
                    WHEN DUP_VAL_ON_INDEX THEN
                        SELECT ID_CARRITO INTO O_ID_CARRITO FROM CARRITO
                         WHERE ID_USUARIO = P_ID_USUARIO AND ID_SITIO = P_ID_SITIO AND ESTADO = 'ABIERTO';
                END;
        END;
    END SP_OBTENER_O_CREAR;

    PROCEDURE SP_CREAR_PERSONALIZACION (
        P_ID_ARCHIVO_LADO_A IN PERSONALIZACION.ID_ARCHIVO_LADO_A%TYPE,
        P_ID_ARCHIVO_LADO_B IN PERSONALIZACION.ID_ARCHIVO_LADO_B%TYPE,
        P_MENSAJE_LADO_A IN PERSONALIZACION.MENSAJE_LADO_A%TYPE,
        P_MENSAJE_LADO_B IN PERSONALIZACION.MENSAJE_LADO_B%TYPE,
        P_CONFIG_LADO_A IN PERSONALIZACION.CONFIG_LADO_A%TYPE,
        P_CONFIG_LADO_B IN PERSONALIZACION.CONFIG_LADO_B%TYPE,
        O_ID_PERSONALIZACION OUT PERSONALIZACION.ID_PERSONALIZACION%TYPE
    ) AS
    BEGIN
        IF P_ID_ARCHIVO_LADO_A IS NULL AND P_ID_ARCHIVO_LADO_B IS NULL
           AND P_MENSAJE_LADO_A IS NULL AND P_MENSAJE_LADO_B IS NULL THEN
            RAISE_APPLICATION_ERROR(-20402, 'Debe ingresar imagen o mensaje.');
        END IF;
        INSERT INTO PERSONALIZACION (
            ID_ARCHIVO_LADO_A, ID_ARCHIVO_LADO_B, MENSAJE_LADO_A,
            MENSAJE_LADO_B, CONFIG_LADO_A, CONFIG_LADO_B
        ) VALUES (
            P_ID_ARCHIVO_LADO_A, P_ID_ARCHIVO_LADO_B, P_MENSAJE_LADO_A,
            P_MENSAJE_LADO_B, P_CONFIG_LADO_A, P_CONFIG_LADO_B
        ) RETURNING ID_PERSONALIZACION INTO O_ID_PERSONALIZACION;
    END SP_CREAR_PERSONALIZACION;

    PROCEDURE SP_AGREGAR_PRODUCTO (
        P_ID_CARRITO IN CARRITO_DETALLE.ID_CARRITO%TYPE,
        P_ID_PRODUCTO IN CARRITO_DETALLE.ID_PRODUCTO%TYPE,
        P_ID_PERSONALIZACION IN CARRITO_DETALLE.ID_PERSONALIZACION%TYPE,
        P_CANTIDAD IN CARRITO_DETALLE.CANTIDAD%TYPE,
        P_PRECIO_PERSONALIZA IN CARRITO_DETALLE.PRECIO_PERSONALIZA%TYPE,
        O_ID_CARRITO_DETALLE OUT CARRITO_DETALLE.ID_CARRITO_DETALLE%TYPE
    ) AS
        V_SITIO_CARRITO CARRITO.ID_SITIO%TYPE;
        V_SITIO_PRODUCTO PRODUCTO.ID_SITIO%TYPE;
        V_PRECIO PRODUCTO.PRECIO_BASE%TYPE;
        V_ACTIVO PRODUCTO.ACTIVO%TYPE;
        V_BLOQUEADA PERSONALIZACION.BLOQUEADA%TYPE;
    BEGIN
        IF P_CANTIDAD <= 0 OR P_PRECIO_PERSONALIZA < 0 THEN
            RAISE_APPLICATION_ERROR(-20403, 'Cantidad o precio no valido.');
        END IF;
        SELECT ID_SITIO INTO V_SITIO_CARRITO FROM CARRITO
         WHERE ID_CARRITO = P_ID_CARRITO AND ESTADO = 'ABIERTO' FOR UPDATE;
        SELECT ID_SITIO, PRECIO_BASE, ACTIVO INTO V_SITIO_PRODUCTO, V_PRECIO, V_ACTIVO
          FROM PRODUCTO WHERE ID_PRODUCTO = P_ID_PRODUCTO;
        IF V_SITIO_CARRITO <> V_SITIO_PRODUCTO OR V_ACTIVO <> 'S' THEN
            RAISE_APPLICATION_ERROR(-20404, 'El producto no pertenece al sitio o esta inactivo.');
        END IF;
        IF P_ID_PERSONALIZACION IS NOT NULL THEN
            SELECT BLOQUEADA INTO V_BLOQUEADA FROM PERSONALIZACION
             WHERE ID_PERSONALIZACION = P_ID_PERSONALIZACION;
            IF V_BLOQUEADA = 'S' THEN RAISE_APPLICATION_ERROR(-20405, 'La personalizacion esta bloqueada.'); END IF;
        END IF;
        INSERT INTO CARRITO_DETALLE (
            ID_CARRITO, ID_PRODUCTO, ID_PERSONALIZACION,
            CANTIDAD, PRECIO_UNITARIO, PRECIO_PERSONALIZA
        ) VALUES (
            P_ID_CARRITO, P_ID_PRODUCTO, P_ID_PERSONALIZACION,
            P_CANTIDAD, V_PRECIO, P_PRECIO_PERSONALIZA
        ) RETURNING ID_CARRITO_DETALLE INTO O_ID_CARRITO_DETALLE;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20406, 'No existe el carrito, producto o personalizacion.');
    END SP_AGREGAR_PRODUCTO;

    PROCEDURE SP_ACTUALIZAR_CANTIDAD (
        P_ID_CARRITO_DETALLE IN CARRITO_DETALLE.ID_CARRITO_DETALLE%TYPE,
        P_CANTIDAD IN CARRITO_DETALLE.CANTIDAD%TYPE
    ) AS
    BEGIN
        IF P_CANTIDAD <= 0 THEN RAISE_APPLICATION_ERROR(-20407, 'La cantidad debe ser mayor que cero.'); END IF;
        UPDATE CARRITO_DETALLE CD SET CANTIDAD = P_CANTIDAD
         WHERE CD.ID_CARRITO_DETALLE = P_ID_CARRITO_DETALLE
           AND EXISTS (SELECT 1 FROM CARRITO C WHERE C.ID_CARRITO = CD.ID_CARRITO AND C.ESTADO = 'ABIERTO');
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20408, 'El detalle no existe o el carrito esta cerrado.'); END IF;
    END SP_ACTUALIZAR_CANTIDAD;

    PROCEDURE SP_ELIMINAR_DETALLE (P_ID_CARRITO_DETALLE IN CARRITO_DETALLE.ID_CARRITO_DETALLE%TYPE) AS
    BEGIN
        DELETE FROM CARRITO_DETALLE CD
         WHERE CD.ID_CARRITO_DETALLE = P_ID_CARRITO_DETALLE
           AND EXISTS (SELECT 1 FROM CARRITO C WHERE C.ID_CARRITO = CD.ID_CARRITO AND C.ESTADO = 'ABIERTO');
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20409, 'El detalle no existe o el carrito esta cerrado.'); END IF;
    END SP_ELIMINAR_DETALLE;

    PROCEDURE SP_OBTENER_CARRITO (P_ID_CARRITO IN CARRITO.ID_CARRITO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT C.ID_CARRITO, C.ID_USUARIO, C.ID_SITIO, C.ESTADO,
                   CD.ID_CARRITO_DETALLE, CD.ID_PRODUCTO, P.SKU,
                   P.NOMBRE PRODUCTO, CD.ID_PERSONALIZACION, CD.CANTIDAD,
                   CD.PRECIO_UNITARIO, CD.PRECIO_PERSONALIZA, CD.SUBTOTAL,
                   SUM(CD.SUBTOTAL) OVER (PARTITION BY C.ID_CARRITO) TOTAL_CARRITO
              FROM CARRITO C
              LEFT JOIN CARRITO_DETALLE CD ON CD.ID_CARRITO = C.ID_CARRITO
              LEFT JOIN PRODUCTO P ON P.ID_PRODUCTO = CD.ID_PRODUCTO
             WHERE C.ID_CARRITO = P_ID_CARRITO
             ORDER BY CD.FECHA_AGREGADO, CD.ID_CARRITO_DETALLE;
    END SP_OBTENER_CARRITO;

    PROCEDURE SP_ABANDONAR_CARRITO (P_ID_CARRITO IN CARRITO.ID_CARRITO%TYPE) AS
    BEGIN
        UPDATE CARRITO SET ESTADO = 'ABANDONADO'
         WHERE ID_CARRITO = P_ID_CARRITO AND ESTADO = 'ABIERTO';
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20410, 'El carrito no existe o esta cerrado.'); END IF;
    END SP_ABANDONAR_CARRITO;
END PKG_CARRITO;
