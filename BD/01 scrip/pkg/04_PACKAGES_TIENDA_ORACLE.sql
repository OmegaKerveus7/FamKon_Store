            ID_ARCHIVO_LADO_A, ID_ARCHIVO_LADO_B, MENSAJE_LADO_A,
            MENSAJE_LADO_B, CONFIG_LADO_A, CONFIG_LADO_B
        ) VALUES (
            P_ID_ARCHIVO_LADO_A, P_ID_ARCHIVO_LADO_B, P_MENSAJE_LADO_A,
            P_MENSAJE_LADO_B, P_CONFIG_LADO_A, P_CONFIG_LADO_B
        ) RETURNING ID_PERSONALIZACION INTO O_ID_PERSONALIZACION;
    END SP_CREAR_PERSONALIZACION;

    PROCEDURE SP_AGREGAR_PRODUCTO (
        P_ID_CARRITO IN CARRITO_DETALLE.ID_CARRITO%TYPE,
        P_ID_PRODUCTO IN CARRITO_DETALLE.ID_PRODUCTO%TYPE,
        P_ID_PERSONALIZACION IN CARRITO_DETALLE.ID_PERSONALIZACION%TYPE,
        P_CANTIDAD IN CARRITO_DETALLE.CANTIDAD%TYPE,
        P_PRECIO_PERSONALIZA IN CARRITO_DETALLE.PRECIO_PERSONALIZA%TYPE,
        O_ID_CARRITO_DETALLE OUT CARRITO_DETALLE.ID_CARRITO_DETALLE%TYPE
    ) AS
        V_SITIO_CARRITO CARRITO.ID_SITIO%TYPE;
        V_SITIO_PRODUCTO PRODUCTO.ID_SITIO%TYPE;
        V_PRECIO PRODUCTO.PRECIO_BASE%TYPE;
        V_ACTIVO PRODUCTO.ACTIVO%TYPE;
        V_BLOQUEADA PERSONALIZACION.BLOQUEADA%TYPE;
    BEGIN
        IF P_CANTIDAD <= 0 OR P_PRECIO_PERSONALIZA < 0 THEN
            RAISE_APPLICATION_ERROR(-20403, 'Cantidad o precio no valido.');
        END IF;
        SELECT ID_SITIO INTO V_SITIO_CARRITO FROM CARRITO
         WHERE ID_CARRITO = P_ID_CARRITO AND ESTADO = 'ABIERTO' FOR UPDATE;
        SELECT ID_SITIO, PRECIO_BASE, ACTIVO INTO V_SITIO_PRODUCTO, V_PRECIO, V_ACTIVO
          FROM PRODUCTO WHERE ID_PRODUCTO = P_ID_PRODUCTO;
        IF V_SITIO_CARRITO <> V_SITIO_PRODUCTO OR V_ACTIVO <> 'S' THEN
            RAISE_APPLICATION_ERROR(-20404, 'El producto no pertenece al sitio o esta inactivo.');
        END IF;
        IF P_ID_PERSONALIZACION IS NOT NULL THEN
            SELECT BLOQUEADA INTO V_BLOQUEADA FROM PERSONALIZACION
             WHERE ID_PERSONALIZACION = P_ID_PERSONALIZACION;
            IF V_BLOQUEADA = 'S' THEN RAISE_APPLICATION_ERROR(-20405, 'La personalizacion esta bloqueada.'); END IF;
        END IF;
        INSERT INTO CARRITO_DETALLE (
            ID_CARRITO, ID_PRODUCTO, ID_PERSONALIZACION,
            CANTIDAD, PRECIO_UNITARIO, PRECIO_PERSONALIZA
        ) VALUES (
