CREATE OR REPLACE PACKAGE BODY PKG_SEGURIDAD AS
    PROCEDURE SP_CREAR_USUARIO (
        P_ID_SITIO IN USUARIO.ID_SITIO%TYPE,
        P_CORREO IN USUARIO.CORREO%TYPE,
        P_TELEFONO IN USUARIO.TELEFONO%TYPE,
        P_FECHA_NACIMIENTO IN USUARIO.FECHA_NACIMIENTO%TYPE,
        P_NICKNAME IN USUARIO.NICKNAME%TYPE,
        P_PASSWORD_HASH IN USUARIO.PASSWORD_HASH%TYPE,
        P_TOKEN_QR_HASH IN USUARIO.TOKEN_QR_HASH%TYPE,
        P_NOTIFICA_EMAIL IN USUARIO.NOTIFICA_EMAIL%TYPE,
        P_NOTIFICA_WHATSAPP IN USUARIO.NOTIFICA_WHATSAPP%TYPE,
        O_ID_USUARIO OUT USUARIO.ID_USUARIO%TYPE
    ) AS
        V_ID_ROL ROL.ID_ROL%TYPE;
        V_EXISTE NUMBER;
    BEGIN
        IF P_NOTIFICA_EMAIL NOT IN ('S','N') OR P_NOTIFICA_WHATSAPP NOT IN ('S','N')
           OR (P_NOTIFICA_EMAIL = 'N' AND P_NOTIFICA_WHATSAPP = 'N') THEN
            RAISE_APPLICATION_ERROR(-20101, 'Debe habilitar al menos un medio de notificacion.');
        END IF;

        SELECT COUNT(*) INTO V_EXISTE FROM SITIO
         WHERE ID_SITIO = P_ID_SITIO AND ACTIVO = 'S';
        IF V_EXISTE = 0 THEN
            RAISE_APPLICATION_ERROR(-20102, 'El sitio no existe o esta inactivo.');
        END IF;

        SELECT ID_ROL INTO V_ID_ROL FROM ROL
         WHERE CODIGO = 'COMPRADOR' AND ACTIVO = 'S';

        INSERT INTO USUARIO (
            ID_SITIO, CORREO, TELEFONO, FECHA_NACIMIENTO, NICKNAME,
            PASSWORD_HASH, TOKEN_QR_HASH, NOTIFICA_EMAIL, NOTIFICA_WHATSAPP
        ) VALUES (
            P_ID_SITIO, TRIM(P_CORREO), TRIM(P_TELEFONO), P_FECHA_NACIMIENTO,
            TRIM(P_NICKNAME), P_PASSWORD_HASH, P_TOKEN_QR_HASH,
            P_NOTIFICA_EMAIL, P_NOTIFICA_WHATSAPP
        ) RETURNING ID_USUARIO INTO O_ID_USUARIO;

        INSERT INTO USUARIO_ROL (ID_USUARIO, ID_ROL)
        VALUES (O_ID_USUARIO, V_ID_ROL);
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20103, 'El correo, nickname o token QR ya esta registrado.');
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20104, 'No existe el rol activo COMPRADOR.');
    END SP_CREAR_USUARIO;

    PROCEDURE SP_ASIGNAR_ROL (
        P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
        P_CODIGO_ROL IN ROL.CODIGO%TYPE
    ) AS
        V_ID_ROL ROL.ID_ROL%TYPE;
        V_EXISTE NUMBER;
    BEGIN
        SELECT COUNT(*) INTO V_EXISTE FROM USUARIO WHERE ID_USUARIO = P_ID_USUARIO;
        IF V_EXISTE = 0 THEN RAISE_APPLICATION_ERROR(-20105, 'El usuario no existe.'); END IF;

        SELECT ID_ROL INTO V_ID_ROL FROM ROL
         WHERE CODIGO = UPPER(TRIM(P_CODIGO_ROL)) AND ACTIVO = 'S';

        MERGE INTO USUARIO_ROL UR
        USING (SELECT P_ID_USUARIO ID_USUARIO, V_ID_ROL ID_ROL FROM DUAL) X
           ON (UR.ID_USUARIO = X.ID_USUARIO AND UR.ID_ROL = X.ID_ROL)
        WHEN NOT MATCHED THEN
            INSERT (ID_USUARIO, ID_ROL) VALUES (X.ID_USUARIO, X.ID_ROL);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20106, 'El rol no existe o esta inactivo.');
    END SP_ASIGNAR_ROL;

    PROCEDURE SP_CAMBIAR_ESTADO_USUARIO (
        P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
        P_ACTIVO IN USUARIO.ACTIVO%TYPE,
        P_BLOQUEADO IN USUARIO.BLOQUEADO%TYPE
    ) AS
    BEGIN
        IF P_ACTIVO NOT IN ('S','N') OR P_BLOQUEADO NOT IN ('S','N') THEN
            RAISE_APPLICATION_ERROR(-20107, 'Los estados deben ser S o N.');
        END IF;
        UPDATE USUARIO SET ACTIVO = P_ACTIVO, BLOQUEADO = P_BLOQUEADO
         WHERE ID_USUARIO = P_ID_USUARIO;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20108, 'El usuario no existe.'); END IF;
    END SP_CAMBIAR_ESTADO_USUARIO;

    PROCEDURE SP_REGISTRAR_ACCESO (
        P_ID_USUARIO IN BITACORA_ACCESO.ID_USUARIO%TYPE,
        P_IDENTIFICADOR IN BITACORA_ACCESO.IDENTIFICADOR%TYPE,
        P_METODO_ACCESO IN BITACORA_ACCESO.METODO_ACCESO%TYPE,
        P_RESULTADO IN BITACORA_ACCESO.RESULTADO%TYPE,
        P_DIRECCION_IP IN BITACORA_ACCESO.DIRECCION_IP%TYPE,
        P_UBICACION IN BITACORA_ACCESO.UBICACION%TYPE,
        P_USER_AGENT IN BITACORA_ACCESO.USER_AGENT%TYPE,
        P_MOTIVO IN BITACORA_ACCESO.MOTIVO%TYPE,
        O_ID_BITACORA OUT BITACORA_ACCESO.ID_BITACORA%TYPE
    ) AS
    BEGIN
        INSERT INTO BITACORA_ACCESO (
            ID_USUARIO, IDENTIFICADOR, METODO_ACCESO, RESULTADO,
            DIRECCION_IP, UBICACION, USER_AGENT, MOTIVO
        ) VALUES (
            P_ID_USUARIO, P_IDENTIFICADOR, UPPER(TRIM(P_METODO_ACCESO)), P_RESULTADO,
            P_DIRECCION_IP, P_UBICACION, P_USER_AGENT, P_MOTIVO
        ) RETURNING ID_BITACORA INTO O_ID_BITACORA;
    END SP_REGISTRAR_ACCESO;

    PROCEDURE SP_OBTENER_AUTENTICACION (P_IDENTIFICADOR IN VARCHAR2, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT ID_USUARIO, ID_SITIO, CORREO, NICKNAME, PASSWORD_HASH,
                   TOKEN_QR_HASH, ACTIVO, BLOQUEADO, INTENTOS_FALLIDOS, ULTIMO_ACCESO
              FROM USUARIO
             WHERE LOWER(CORREO) = LOWER(TRIM(P_IDENTIFICADOR))
                OR LOWER(NICKNAME) = LOWER(TRIM(P_IDENTIFICADOR));
    END SP_OBTENER_AUTENTICACION;

    PROCEDURE SP_LISTAR_PERMISOS (P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT DISTINCT R.CODIGO CODIGO_ROL, R.NOMBRE ROL,
                   P.CODIGO CODIGO_PERMISO, P.NOMBRE PERMISO, P.MODULO
              FROM USUARIO_ROL UR
              JOIN ROL R ON R.ID_ROL = UR.ID_ROL AND R.ACTIVO = 'S'
              JOIN ROL_PERMISO RP ON RP.ID_ROL = R.ID_ROL
              JOIN PERMISO P ON P.ID_PERMISO = RP.ID_PERMISO AND P.ACTIVO = 'S'
             WHERE UR.ID_USUARIO = P_ID_USUARIO
             ORDER BY P.MODULO, P.CODIGO;
    END SP_LISTAR_PERMISOS;
END PKG_SEGURIDAD;
/
SHOW ERRORS PACKAGE BODY PKG_SEGURIDAD;

CREATE OR REPLACE PACKAGE BODY PKG_ARCHIVO AS
    PROCEDURE SP_GUARDAR_ARCHIVO (
        P_ID_USUARIO_CARGA IN ARCHIVO.ID_USUARIO_CARGA%TYPE,
        P_TIPO_ARCHIVO IN ARCHIVO.TIPO_ARCHIVO%TYPE,
        P_NOMBRE_ARCHIVO IN ARCHIVO.NOMBRE_ARCHIVO%TYPE,
        P_MIME_TYPE IN ARCHIVO.MIME_TYPE%TYPE,
        P_HASH_SHA256 IN ARCHIVO.HASH_SHA256%TYPE,
        P_CONTENIDO IN ARCHIVO.CONTENIDO%TYPE,
        O_ID_ARCHIVO OUT ARCHIVO.ID_ARCHIVO%TYPE
    ) AS
        V_TAMANO ARCHIVO.TAMANO_BYTES%TYPE;
    BEGIN
        IF P_CONTENIDO IS NULL THEN RAISE_APPLICATION_ERROR(-20201, 'El contenido es obligatorio.'); END IF;
        V_TAMANO := DBMS_LOB.GETLENGTH(P_CONTENIDO);
        INSERT INTO ARCHIVO (
            ID_USUARIO_CARGA, TIPO_ARCHIVO, NOMBRE_ARCHIVO,
            MIME_TYPE, TAMANO_BYTES, HASH_SHA256, CONTENIDO
        ) VALUES (
            P_ID_USUARIO_CARGA, UPPER(TRIM(P_TIPO_ARCHIVO)), TRIM(P_NOMBRE_ARCHIVO),
            LOWER(TRIM(P_MIME_TYPE)), V_TAMANO, LOWER(TRIM(P_HASH_SHA256)), P_CONTENIDO
        ) RETURNING ID_ARCHIVO INTO O_ID_ARCHIVO;
    END SP_GUARDAR_ARCHIVO;

    PROCEDURE SP_OBTENER_ARCHIVO (P_ID_ARCHIVO IN ARCHIVO.ID_ARCHIVO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT ID_ARCHIVO, ID_USUARIO_CARGA, TIPO_ARCHIVO, NOMBRE_ARCHIVO,
                   MIME_TYPE, TAMANO_BYTES, HASH_SHA256, CONTENIDO, FECHA_CARGA
              FROM ARCHIVO WHERE ID_ARCHIVO = P_ID_ARCHIVO AND ACTIVO = 'S';
    END SP_OBTENER_ARCHIVO;

    PROCEDURE SP_CAMBIAR_ESTADO (P_ID_ARCHIVO IN ARCHIVO.ID_ARCHIVO%TYPE, P_ACTIVO IN ARCHIVO.ACTIVO%TYPE) AS
    BEGIN
        IF P_ACTIVO NOT IN ('S','N') THEN RAISE_APPLICATION_ERROR(-20202, 'El estado debe ser S o N.'); END IF;
        UPDATE ARCHIVO SET ACTIVO = P_ACTIVO WHERE ID_ARCHIVO = P_ID_ARCHIVO;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20203, 'El archivo no existe.'); END IF;
    END SP_CAMBIAR_ESTADO;
END PKG_ARCHIVO;
/
SHOW ERRORS PACKAGE BODY PKG_ARCHIVO;

CREATE OR REPLACE PACKAGE BODY PKG_CATALOGO AS
    PROCEDURE SP_LISTAR_PRODUCTOS (
        P_ID_SITIO IN PRODUCTO.ID_SITIO%TYPE,
        P_ID_CATEGORIA IN PRODUCTO.ID_CATEGORIA%TYPE,
        P_SOLO_ACTIVOS IN CHAR,
        O_DATOS OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT P.ID_PRODUCTO, P.ID_SITIO, P.ID_CATEGORIA,
                   C.CODIGO CODIGO_CATEGORIA, C.NOMBRE CATEGORIA,
                   P.ID_ARCHIVO_IMAGEN, P.SKU, P.NOMBRE, P.DESCRIPCION,
                   P.PRECIO_BASE, P.PERMITE_LADO_A, P.PERMITE_LADO_B, P.ACTIVO
              FROM PRODUCTO P
              JOIN CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
             WHERE P.ID_SITIO = P_ID_SITIO
               AND (P_ID_CATEGORIA IS NULL OR P.ID_CATEGORIA = P_ID_CATEGORIA)
               AND (P_SOLO_ACTIVOS = 'N' OR P.ACTIVO = 'S')
             ORDER BY C.NOMBRE, P.NOMBRE;
    END SP_LISTAR_PRODUCTOS;

    PROCEDURE SP_OBTENER_PRODUCTO (P_ID_PRODUCTO IN PRODUCTO.ID_PRODUCTO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT P.ID_PRODUCTO, P.ID_SITIO, S.NOMBRE SITIO,
                   P.ID_CATEGORIA, C.NOMBRE CATEGORIA, P.ID_ARCHIVO_IMAGEN,
                   P.SKU, P.NOMBRE, P.DESCRIPCION, P.PRECIO_BASE,
                   P.PERMITE_LADO_A, P.PERMITE_LADO_B, P.ACTIVO,
                   P.FECHA_CREACION, P.FECHA_MODIFICACION
              FROM PRODUCTO P
              JOIN SITIO S ON S.ID_SITIO = P.ID_SITIO
              JOIN CATEGORIA_PRODUCTO C ON C.ID_CATEGORIA = P.ID_CATEGORIA
             WHERE P.ID_PRODUCTO = P_ID_PRODUCTO;
    END SP_OBTENER_PRODUCTO;

    PROCEDURE SP_CREAR_PRODUCTO (
        P_ID_SITIO IN PRODUCTO.ID_SITIO%TYPE,
        P_ID_CATEGORIA IN PRODUCTO.ID_CATEGORIA%TYPE,
        P_ID_ARCHIVO_IMAGEN IN PRODUCTO.ID_ARCHIVO_IMAGEN%TYPE,
        P_SKU IN PRODUCTO.SKU%TYPE,
        P_NOMBRE IN PRODUCTO.NOMBRE%TYPE,
        P_DESCRIPCION IN PRODUCTO.DESCRIPCION%TYPE,
        P_PRECIO_BASE IN PRODUCTO.PRECIO_BASE%TYPE,
        P_PERMITE_LADO_A IN PRODUCTO.PERMITE_LADO_A%TYPE,
        P_PERMITE_LADO_B IN PRODUCTO.PERMITE_LADO_B%TYPE,
        O_ID_PRODUCTO OUT PRODUCTO.ID_PRODUCTO%TYPE
    ) AS
    BEGIN
        IF P_PRECIO_BASE < 0 THEN RAISE_APPLICATION_ERROR(-20301, 'El precio no puede ser negativo.'); END IF;
        INSERT INTO PRODUCTO (
            ID_SITIO, ID_CATEGORIA, ID_ARCHIVO_IMAGEN, SKU, NOMBRE,
            DESCRIPCION, PRECIO_BASE, PERMITE_LADO_A, PERMITE_LADO_B
        ) VALUES (
            P_ID_SITIO, P_ID_CATEGORIA, P_ID_ARCHIVO_IMAGEN, UPPER(TRIM(P_SKU)),
            TRIM(P_NOMBRE), P_DESCRIPCION, P_PRECIO_BASE, P_PERMITE_LADO_A, P_PERMITE_LADO_B
        ) RETURNING ID_PRODUCTO INTO O_ID_PRODUCTO;
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20302, 'Ya existe el SKU en este sitio.');
    END SP_CREAR_PRODUCTO;

    PROCEDURE SP_ACTUALIZAR_PRODUCTO (
        P_ID_PRODUCTO IN PRODUCTO.ID_PRODUCTO%TYPE,
        P_ID_CATEGORIA IN PRODUCTO.ID_CATEGORIA%TYPE,
        P_ID_ARCHIVO_IMAGEN IN PRODUCTO.ID_ARCHIVO_IMAGEN%TYPE,
        P_NOMBRE IN PRODUCTO.NOMBRE%TYPE,
        P_DESCRIPCION IN PRODUCTO.DESCRIPCION%TYPE,
        P_PRECIO_BASE IN PRODUCTO.PRECIO_BASE%TYPE,
        P_PERMITE_LADO_A IN PRODUCTO.PERMITE_LADO_A%TYPE,
        P_PERMITE_LADO_B IN PRODUCTO.PERMITE_LADO_B%TYPE
    ) AS
    BEGIN
        IF P_PRECIO_BASE < 0 THEN RAISE_APPLICATION_ERROR(-20303, 'El precio no puede ser negativo.'); END IF;
        UPDATE PRODUCTO
           SET ID_CATEGORIA = P_ID_CATEGORIA,
               ID_ARCHIVO_IMAGEN = P_ID_ARCHIVO_IMAGEN,
               NOMBRE = TRIM(P_NOMBRE), DESCRIPCION = P_DESCRIPCION,
               PRECIO_BASE = P_PRECIO_BASE, PERMITE_LADO_A = P_PERMITE_LADO_A,
               PERMITE_LADO_B = P_PERMITE_LADO_B
         WHERE ID_PRODUCTO = P_ID_PRODUCTO;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20304, 'El producto no existe.'); END IF;
    END SP_ACTUALIZAR_PRODUCTO;

    PROCEDURE SP_CAMBIAR_ESTADO_PRODUCTO (P_ID_PRODUCTO IN PRODUCTO.ID_PRODUCTO%TYPE, P_ACTIVO IN PRODUCTO.ACTIVO%TYPE) AS
    BEGIN
        IF P_ACTIVO NOT IN ('S','N') THEN RAISE_APPLICATION_ERROR(-20305, 'El estado debe ser S o N.'); END IF;
        UPDATE PRODUCTO SET ACTIVO = P_ACTIVO WHERE ID_PRODUCTO = P_ID_PRODUCTO;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20306, 'El producto no existe.'); END IF;
    END SP_CAMBIAR_ESTADO_PRODUCTO;

    PROCEDURE SP_LISTAR_CATEGORIAS (P_SOLO_ACTIVAS IN CHAR, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT ID_CATEGORIA, CODIGO, NOMBRE, DESCRIPCION, ACTIVO
              FROM CATEGORIA_PRODUCTO
             WHERE P_SOLO_ACTIVAS = 'N' OR ACTIVO = 'S'
             ORDER BY NOMBRE;
    END SP_LISTAR_CATEGORIAS;

    PROCEDURE SP_LISTAR_AREAS_ENTREGA (
        P_ID_SITIO IN AREA_ENTREGA.ID_SITIO%TYPE,
        P_SOLO_ACTIVAS IN CHAR,
        O_DATOS OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT ID_AREA_ENTREGA, ID_SITIO, CODIGO, NOMBRE,
                   TIPO_AREA, REFERENCIA, CARGO_ENTREGA, ACTIVO
              FROM AREA_ENTREGA
             WHERE ID_SITIO = P_ID_SITIO
               AND (P_SOLO_ACTIVAS = 'N' OR ACTIVO = 'S')
             ORDER BY NOMBRE;
    END SP_LISTAR_AREAS_ENTREGA;

    PROCEDURE SP_LISTAR_METODOS_PAGO (P_SOLO_ACTIVOS IN CHAR, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT ID_METODO_PAGO, CODIGO, NOMBRE, REQUIERE_PROVEEDOR, ACTIVO
              FROM METODO_PAGO
             WHERE P_SOLO_ACTIVOS = 'N' OR ACTIVO = 'S'
             ORDER BY NOMBRE;
    END SP_LISTAR_METODOS_PAGO;
END PKG_CATALOGO;
