CREATE OR REPLACE PACKAGE BODY PKG_PAGO_ENTREGA AS
    PROCEDURE SP_REGISTRAR_PAGO (
        P_ID_PEDIDO IN PAGO.ID_PEDIDO%TYPE,
        P_CODIGO_METODO IN METODO_PAGO.CODIGO%TYPE,
        P_CODIGO_ESTADO IN ESTADO_PAGO.CODIGO%TYPE,
        P_MONTO IN PAGO.MONTO%TYPE,
        P_PROVEEDOR_PAGO IN PAGO.PROVEEDOR_PAGO%TYPE,
        P_REFERENCIA_PROV IN PAGO.REFERENCIA_PROV%TYPE,
        P_MARCA_TARJETA IN PAGO.MARCA_TARJETA%TYPE,
        P_ULTIMOS_4 IN PAGO.ULTIMOS_4%TYPE,
        P_OBSERVACIONES IN PAGO.OBSERVACIONES%TYPE,
        O_ID_PAGO OUT PAGO.ID_PAGO%TYPE
    ) AS
        V_METODO METODO_PAGO.ID_METODO_PAGO%TYPE;
        V_REQUIERE METODO_PAGO.REQUIERE_PROVEEDOR%TYPE;
        V_ESTADO ESTADO_PAGO.ID_ESTADO_PAGO%TYPE;
        V_TOTAL PEDIDO.TOTAL%TYPE;
        V_MONEDA PEDIDO.COD_MONEDA%TYPE;
    BEGIN
        SELECT TOTAL, COD_MONEDA INTO V_TOTAL, V_MONEDA FROM PEDIDO WHERE ID_PEDIDO = P_ID_PEDIDO;
        IF P_MONTO <= 0 OR P_MONTO > V_TOTAL THEN
            RAISE_APPLICATION_ERROR(-20601, 'El monto no es valido para el pedido.');
        END IF;
        SELECT ID_METODO_PAGO, REQUIERE_PROVEEDOR INTO V_METODO, V_REQUIERE
          FROM METODO_PAGO WHERE CODIGO = UPPER(TRIM(P_CODIGO_METODO)) AND ACTIVO = 'S';
        IF V_REQUIERE = 'S' AND (P_PROVEEDOR_PAGO IS NULL OR P_REFERENCIA_PROV IS NULL) THEN
            RAISE_APPLICATION_ERROR(-20602, 'El metodo requiere proveedor y referencia.');
        END IF;
        SELECT ID_ESTADO_PAGO INTO V_ESTADO FROM ESTADO_PAGO
         WHERE CODIGO = UPPER(TRIM(P_CODIGO_ESTADO)) AND ACTIVO = 'S';
        INSERT INTO PAGO (
            ID_PEDIDO, ID_METODO_PAGO, ID_ESTADO_PAGO, MONTO, COD_MONEDA,
            PROVEEDOR_PAGO, REFERENCIA_PROV, MARCA_TARJETA, ULTIMOS_4,
            FECHA_CONFIRMACION, OBSERVACIONES
        ) VALUES (
            P_ID_PEDIDO, V_METODO, V_ESTADO, P_MONTO, V_MONEDA,
            P_PROVEEDOR_PAGO, P_REFERENCIA_PROV, P_MARCA_TARJETA, P_ULTIMOS_4,
            CASE WHEN UPPER(TRIM(P_CODIGO_ESTADO)) IN ('APROBADO','PAGADO_EFECTIVO')
                 THEN SYSTIMESTAMP END,
            P_OBSERVACIONES
        ) RETURNING ID_PAGO INTO O_ID_PAGO;
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN RAISE_APPLICATION_ERROR(-20603, 'La referencia ya fue registrada.');
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20604, 'No existe el pedido, metodo o estado.');
    END SP_REGISTRAR_PAGO;

    PROCEDURE SP_CAMBIAR_ESTADO_PAGO (
        P_ID_PAGO IN PAGO.ID_PAGO%TYPE,
        P_CODIGO_ESTADO IN ESTADO_PAGO.CODIGO%TYPE,
        P_OBSERVACIONES IN PAGO.OBSERVACIONES%TYPE
    ) AS
        V_ESTADO ESTADO_PAGO.ID_ESTADO_PAGO%TYPE;
    BEGIN
        SELECT ID_ESTADO_PAGO INTO V_ESTADO FROM ESTADO_PAGO
         WHERE CODIGO = UPPER(TRIM(P_CODIGO_ESTADO)) AND ACTIVO = 'S';
        UPDATE PAGO
           SET ID_ESTADO_PAGO = V_ESTADO,
               FECHA_CONFIRMACION = CASE
                   WHEN UPPER(TRIM(P_CODIGO_ESTADO)) IN ('APROBADO','PAGADO_EFECTIVO')
                   THEN SYSTIMESTAMP ELSE FECHA_CONFIRMACION END,
               OBSERVACIONES = COALESCE(P_OBSERVACIONES, OBSERVACIONES)
         WHERE ID_PAGO = P_ID_PAGO;
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20605, 'El pago no existe.'); END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20606, 'El estado de pago no existe.');
    END SP_CAMBIAR_ESTADO_PAGO;

    PROCEDURE SP_LISTAR_PAGOS_PEDIDO (P_ID_PEDIDO IN PAGO.ID_PEDIDO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT PG.ID_PAGO, PG.ID_PEDIDO, MP.CODIGO CODIGO_METODO,
                   MP.NOMBRE METODO_PAGO, EP.CODIGO CODIGO_ESTADO,
                   EP.NOMBRE ESTADO_PAGO, PG.MONTO, PG.COD_MONEDA,
                   PG.PROVEEDOR_PAGO, PG.REFERENCIA_PROV, PG.MARCA_TARJETA,
                   PG.ULTIMOS_4, PG.FECHA_REGISTRO, PG.FECHA_CONFIRMACION, PG.OBSERVACIONES
              FROM PAGO PG
              JOIN METODO_PAGO MP ON MP.ID_METODO_PAGO = PG.ID_METODO_PAGO
              JOIN ESTADO_PAGO EP ON EP.ID_ESTADO_PAGO = PG.ID_ESTADO_PAGO
             WHERE PG.ID_PEDIDO = P_ID_PEDIDO ORDER BY PG.FECHA_REGISTRO DESC;
    END SP_LISTAR_PAGOS_PEDIDO;

    PROCEDURE SP_ASIGNAR_ENTREGA (
        P_ID_PEDIDO IN ENTREGA.ID_PEDIDO%TYPE,
        P_ID_REPARTIDOR IN ENTREGA.ID_REPARTIDOR%TYPE,
        O_ID_ENTREGA OUT ENTREGA.ID_ENTREGA%TYPE
    ) AS
        V_AREA PEDIDO.ID_AREA_ENTREGA%TYPE;
        V_ESTADO ESTADO_ENTREGA.ID_ESTADO_ENTREGA%TYPE;
        V_INTENTO ENTREGA.NUMERO_INTENTO%TYPE;
        V_REPARTIDOR NUMBER;
    BEGIN
        SELECT ID_AREA_ENTREGA INTO V_AREA FROM PEDIDO WHERE ID_PEDIDO = P_ID_PEDIDO FOR UPDATE;
        SELECT COUNT(*) INTO V_REPARTIDOR
          FROM USUARIO U JOIN USUARIO_ROL UR ON UR.ID_USUARIO = U.ID_USUARIO
          JOIN ROL R ON R.ID_ROL = UR.ID_ROL
         WHERE U.ID_USUARIO = P_ID_REPARTIDOR AND U.ACTIVO = 'S' AND U.BLOQUEADO = 'N'
           AND R.CODIGO = 'REPARTIDOR' AND R.ACTIVO = 'S';
        IF V_REPARTIDOR = 0 THEN RAISE_APPLICATION_ERROR(-20607, 'El usuario no es repartidor activo.'); END IF;
        SELECT ID_ESTADO_ENTREGA INTO V_ESTADO FROM ESTADO_ENTREGA
         WHERE CODIGO = 'ASIGNADA' AND ACTIVO = 'S';
        SELECT NVL(MAX(NUMERO_INTENTO),0) + 1 INTO V_INTENTO FROM ENTREGA WHERE ID_PEDIDO = P_ID_PEDIDO;
        INSERT INTO ENTREGA (
            ID_PEDIDO, ID_REPARTIDOR, ID_ESTADO_ENTREGA,
            ID_AREA_ENTREGA, NUMERO_INTENTO, FECHA_ASIGNACION
        ) VALUES (
            P_ID_PEDIDO, P_ID_REPARTIDOR, V_ESTADO, V_AREA, V_INTENTO, SYSTIMESTAMP
        ) RETURNING ID_ENTREGA INTO O_ID_ENTREGA;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20608, 'No existe el pedido o estado ASIGNADA.');
    END SP_ASIGNAR_ENTREGA;

    PROCEDURE SP_REGISTRAR_RESULTADO_ENTREGA (
        P_ID_ENTREGA IN ENTREGA.ID_ENTREGA%TYPE,
        P_CODIGO_ESTADO IN ESTADO_ENTREGA.CODIGO%TYPE,
        P_ID_ARCHIVO_EVIDENCIA IN ENTREGA.ID_ARCHIVO_EVIDENCIA%TYPE,
        P_MONTO_EFECTIVO IN ENTREGA.MONTO_EFECTIVO%TYPE,
        P_OBSERVACIONES IN ENTREGA.OBSERVACIONES%TYPE,
        P_ID_USUARIO_ACTOR IN USUARIO.ID_USUARIO%TYPE
    ) AS
        V_ESTADO ESTADO_ENTREGA.ID_ESTADO_ENTREGA%TYPE;
        V_PEDIDO ENTREGA.ID_PEDIDO%TYPE;
        V_CODIGO ESTADO_ENTREGA.CODIGO%TYPE;
    BEGIN
        V_CODIGO := UPPER(TRIM(P_CODIGO_ESTADO));
        SELECT ID_PEDIDO INTO V_PEDIDO FROM ENTREGA WHERE ID_ENTREGA = P_ID_ENTREGA FOR UPDATE;
        SELECT ID_ESTADO_ENTREGA INTO V_ESTADO FROM ESTADO_ENTREGA
         WHERE CODIGO = V_CODIGO AND ACTIVO = 'S';
        UPDATE ENTREGA
           SET ID_ESTADO_ENTREGA = V_ESTADO,
               ID_ARCHIVO_EVIDENCIA = COALESCE(P_ID_ARCHIVO_EVIDENCIA, ID_ARCHIVO_EVIDENCIA),
               FECHA_INTENTO = SYSTIMESTAMP,
               FECHA_ENTREGA = CASE WHEN V_CODIGO = 'ENTREGADA' THEN SYSTIMESTAMP ELSE FECHA_ENTREGA END,
               MONTO_EFECTIVO = P_MONTO_EFECTIVO,
               OBSERVACIONES = P_OBSERVACIONES
         WHERE ID_ENTREGA = P_ID_ENTREGA;
        IF V_CODIGO = 'ENTREGADA' THEN
            PKG_PEDIDO.SP_CAMBIAR_ESTADO(V_PEDIDO, 'ENTREGADO', P_ID_USUARIO_ACTOR,
                COALESCE(P_OBSERVACIONES, 'Entrega completada.'), NULL);
        ELSIF V_CODIGO = 'NO_ENCONTRADO' THEN
            PKG_PEDIDO.SP_CAMBIAR_ESTADO(V_PEDIDO, 'COMPRADOR_NO_ENCONTRADO', P_ID_USUARIO_ACTOR,
                COALESCE(P_OBSERVACIONES, 'Comprador no encontrado.'), NULL);
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20609, 'No existe la entrega o estado.');
    END SP_REGISTRAR_RESULTADO_ENTREGA;

    PROCEDURE SP_LISTAR_ENTREGAS_REPARTIDOR (
        P_ID_REPARTIDOR IN ENTREGA.ID_REPARTIDOR%TYPE,
        O_DATOS OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT E.ID_ENTREGA, E.ID_PEDIDO, P.NUMERO_PEDIDO, E.NUMERO_INTENTO,
                   EE.CODIGO CODIGO_ESTADO, EE.NOMBRE ESTADO_ENTREGA,
                   AE.NOMBRE AREA_ENTREGA, AE.REFERENCIA, E.FECHA_ASIGNACION,
                   E.FECHA_INTENTO, E.FECHA_ENTREGA, E.MONTO_EFECTIVO, E.OBSERVACIONES
              FROM ENTREGA E JOIN PEDIDO P ON P.ID_PEDIDO = E.ID_PEDIDO
              JOIN ESTADO_ENTREGA EE ON EE.ID_ESTADO_ENTREGA = E.ID_ESTADO_ENTREGA
              JOIN AREA_ENTREGA AE ON AE.ID_AREA_ENTREGA = E.ID_AREA_ENTREGA
             WHERE E.ID_REPARTIDOR = P_ID_REPARTIDOR
             ORDER BY E.FECHA_ASIGNACION DESC, E.ID_ENTREGA DESC;
    END SP_LISTAR_ENTREGAS_REPARTIDOR;
END PKG_PAGO_ENTREGA;
