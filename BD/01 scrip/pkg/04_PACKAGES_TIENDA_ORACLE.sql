        UPDATE CARRITO_DETALLE CD SET CANTIDAD = P_CANTIDAD
         WHERE CD.ID_CARRITO_DETALLE = P_ID_CARRITO_DETALLE
           AND EXISTS (SELECT 1 FROM CARRITO C WHERE C.ID_CARRITO = CD.ID_CARRITO AND C.ESTADO = 'ABIERTO');
        IF SQL%ROWCOUNT = 0 THEN RAISE_APPLICATION_ERROR(-20408, 'El detalle no existe o el carrito esta cerrado.'); END IF;
    END SP_ACTUALIZAR_CANTIDAD;

