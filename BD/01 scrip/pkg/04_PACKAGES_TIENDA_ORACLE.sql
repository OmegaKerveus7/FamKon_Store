CREATE OR REPLACE PACKAGE BODY PKG_PEDIDO AS
    PROCEDURE SP_CREAR_DESDE_CARRITO (
        P_ID_CARRITO IN CARRITO.ID_CARRITO%TYPE,
        P_ID_AREA_ENTREGA IN AREA_ENTREGA.ID_AREA_ENTREGA%TYPE,
        P_NUMERO_PEDIDO IN PEDIDO.NUMERO_PEDIDO%TYPE,
        P_TOKEN_QR_HASH IN PEDIDO.TOKEN_QR_HASH%TYPE,
        P_COD_MONEDA IN PEDIDO.COD_MONEDA%TYPE,
        P_REFERENCIA_ENTREGA IN PEDIDO.REFERENCIA_ENTREGA%TYPE,
        P_OBSERVACIONES IN PEDIDO.OBSERVACIONES%TYPE,
        O_ID_PEDIDO OUT PEDIDO.ID_PEDIDO%TYPE
    ) AS
        V_ID_USUARIO CARRITO.ID_USUARIO%TYPE;
        V_ID_SITIO CARRITO.ID_SITIO%TYPE;
        V_SITIO_AREA AREA_ENTREGA.ID_SITIO%TYPE;
        V_CARGO AREA_ENTREGA.CARGO_ENTREGA%TYPE;
        V_ID_ESTADO ESTADO_PEDIDO.ID_ESTADO_PEDIDO%TYPE;
        V_SUBTOTAL PEDIDO.SUBTOTAL%TYPE;
        V_LINEAS NUMBER;
    BEGIN
        SELECT ID_USUARIO, ID_SITIO INTO V_ID_USUARIO, V_ID_SITIO
          FROM CARRITO WHERE ID_CARRITO = P_ID_CARRITO AND ESTADO = 'ABIERTO' FOR UPDATE;
        SELECT ID_SITIO, CARGO_ENTREGA INTO V_SITIO_AREA, V_CARGO
          FROM AREA_ENTREGA WHERE ID_AREA_ENTREGA = P_ID_AREA_ENTREGA AND ACTIVO = 'S';
        IF V_ID_SITIO <> V_SITIO_AREA THEN
            RAISE_APPLICATION_ERROR(-20501, 'El area no pertenece al sitio del carrito.');
        END IF;
        SELECT COUNT(*), NVL(SUM(SUBTOTAL),0) INTO V_LINEAS, V_SUBTOTAL
          FROM CARRITO_DETALLE WHERE ID_CARRITO = P_ID_CARRITO;
        IF V_LINEAS = 0 THEN RAISE_APPLICATION_ERROR(-20502, 'El carrito no contiene productos.'); END IF;
        SELECT ID_ESTADO_PEDIDO INTO V_ID_ESTADO FROM ESTADO_PEDIDO
         WHERE CODIGO = 'GENERADO' AND ACTIVO = 'S';

        INSERT INTO PEDIDO (
            ID_CARRITO_ORIGEN, ID_USUARIO, ID_SITIO, ID_AREA_ENTREGA,
            ID_ESTADO_PEDIDO, NUMERO_PEDIDO, TOKEN_QR_HASH,
            SUBTOTAL, CARGO_ENTREGA, TOTAL, COD_MONEDA,
            REFERENCIA_ENTREGA, OBSERVACIONES
        ) VALUES (
            P_ID_CARRITO, V_ID_USUARIO, V_ID_SITIO, P_ID_AREA_ENTREGA,
            V_ID_ESTADO, TRIM(P_NUMERO_PEDIDO), P_TOKEN_QR_HASH,
            V_SUBTOTAL, V_CARGO, V_SUBTOTAL + V_CARGO, UPPER(P_COD_MONEDA),
            P_REFERENCIA_ENTREGA, P_OBSERVACIONES
        ) RETURNING ID_PEDIDO INTO O_ID_PEDIDO;

        INSERT INTO PEDIDO_DETALLE (
            ID_PEDIDO, ID_PRODUCTO, ID_PERSONALIZACION, NUMERO_LINEA,
            SKU_PRODUCTO, NOMBRE_PRODUCTO, CANTIDAD,
            PRECIO_UNITARIO, PRECIO_PERSONALIZA
        )
        SELECT O_ID_PEDIDO, CD.ID_PRODUCTO, CD.ID_PERSONALIZACION,
               ROW_NUMBER() OVER (ORDER BY CD.ID_CARRITO_DETALLE),
               P.SKU, P.NOMBRE, CD.CANTIDAD, CD.PRECIO_UNITARIO, CD.PRECIO_PERSONALIZA
          FROM CARRITO_DETALLE CD JOIN PRODUCTO P ON P.ID_PRODUCTO = CD.ID_PRODUCTO
         WHERE CD.ID_CARRITO = P_ID_CARRITO;

        INSERT INTO PEDIDO_ESTADO_HISTORIAL (
            ID_PEDIDO, ID_ESTADO_PEDIDO, ID_USUARIO_ACTOR, COMENTARIO
        ) VALUES (O_ID_PEDIDO, V_ID_ESTADO, V_ID_USUARIO, 'Pedido creado desde el carrito.');

        UPDATE PERSONALIZACION SET BLOQUEADA = 'S'
         WHERE ID_PERSONALIZACION IN (
             SELECT ID_PERSONALIZACION FROM CARRITO_DETALLE
              WHERE ID_CARRITO = P_ID_CARRITO AND ID_PERSONALIZACION IS NOT NULL
         );
        UPDATE CARRITO SET ESTADO = 'CONVERTIDO' WHERE ID_CARRITO = P_ID_CARRITO;
    EXCEPTION
        WHEN DUP_VAL_ON_INDEX THEN
            RAISE_APPLICATION_ERROR(-20503, 'El numero, token QR o carrito ya fue utilizado.');
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20504, 'No existe el carrito, area o estado requerido.');
    END SP_CREAR_DESDE_CARRITO;

    PROCEDURE SP_CAMBIAR_ESTADO (
        P_ID_PEDIDO IN PEDIDO.ID_PEDIDO%TYPE,
        P_CODIGO_ESTADO IN ESTADO_PEDIDO.CODIGO%TYPE,
        P_ID_USUARIO_ACTOR IN PEDIDO_ESTADO_HISTORIAL.ID_USUARIO_ACTOR%TYPE,
        P_COMENTARIO IN PEDIDO_ESTADO_HISTORIAL.COMENTARIO%TYPE,
        P_DIRECCION_IP IN PEDIDO_ESTADO_HISTORIAL.DIRECCION_IP%TYPE
    ) AS
        V_ACTUAL PEDIDO.ID_ESTADO_PEDIDO%TYPE;
        V_FINAL ESTADO_PEDIDO.ES_FINAL%TYPE;
        V_NUEVO ESTADO_PEDIDO.ID_ESTADO_PEDIDO%TYPE;
    BEGIN
        SELECT P.ID_ESTADO_PEDIDO, E.ES_FINAL INTO V_ACTUAL, V_FINAL
          FROM PEDIDO P JOIN ESTADO_PEDIDO E ON E.ID_ESTADO_PEDIDO = P.ID_ESTADO_PEDIDO
         WHERE P.ID_PEDIDO = P_ID_PEDIDO FOR UPDATE OF P.ID_ESTADO_PEDIDO;
        SELECT ID_ESTADO_PEDIDO INTO V_NUEVO FROM ESTADO_PEDIDO
         WHERE CODIGO = UPPER(TRIM(P_CODIGO_ESTADO)) AND ACTIVO = 'S';
        IF V_ACTUAL = V_NUEVO THEN RETURN; END IF;
        IF V_FINAL = 'S' THEN RAISE_APPLICATION_ERROR(-20505, 'El pedido ya esta en estado final.'); END IF;
        UPDATE PEDIDO SET ID_ESTADO_PEDIDO = V_NUEVO WHERE ID_PEDIDO = P_ID_PEDIDO;
        INSERT INTO PEDIDO_ESTADO_HISTORIAL (
            ID_PEDIDO, ID_ESTADO_PEDIDO, ID_USUARIO_ACTOR, COMENTARIO, DIRECCION_IP
        ) VALUES (P_ID_PEDIDO, V_NUEVO, P_ID_USUARIO_ACTOR, P_COMENTARIO, P_DIRECCION_IP);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN RAISE_APPLICATION_ERROR(-20506, 'El pedido o estado no existe.');
    END SP_CAMBIAR_ESTADO;

    PROCEDURE SP_OBTENER_RESUMEN (P_ID_PEDIDO IN PEDIDO.ID_PEDIDO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR SELECT * FROM VW_PEDIDO_RESUMEN WHERE ID_PEDIDO = P_ID_PEDIDO;
    END SP_OBTENER_RESUMEN;

    PROCEDURE SP_OBTENER_DETALLE (P_ID_PEDIDO IN PEDIDO.ID_PEDIDO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT ID_PEDIDO_DETALLE, ID_PEDIDO, ID_PRODUCTO, ID_PERSONALIZACION,
                   NUMERO_LINEA, SKU_PRODUCTO, NOMBRE_PRODUCTO, CANTIDAD,
                   PRECIO_UNITARIO, PRECIO_PERSONALIZA, SUBTOTAL
              FROM PEDIDO_DETALLE WHERE ID_PEDIDO = P_ID_PEDIDO ORDER BY NUMERO_LINEA;
    END SP_OBTENER_DETALLE;

    PROCEDURE SP_LISTAR_POR_USUARIO (P_ID_USUARIO IN PEDIDO.ID_USUARIO%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT * FROM VW_PEDIDO_RESUMEN
             WHERE ID_USUARIO = P_ID_USUARIO ORDER BY FECHA_PEDIDO DESC;
    END SP_LISTAR_POR_USUARIO;

    PROCEDURE SP_CONSULTAR_TRACKING (P_TOKEN_QR_HASH IN PEDIDO.TOKEN_QR_HASH%TYPE, O_DATOS OUT SYS_REFCURSOR) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT T.* FROM VW_TRACKING_PEDIDO T
              JOIN PEDIDO P ON P.ID_PEDIDO = T.ID_PEDIDO
             WHERE P.TOKEN_QR_HASH = P_TOKEN_QR_HASH ORDER BY T.FECHA_ESTADO;
    END SP_CONSULTAR_TRACKING;
END PKG_PEDIDO;
