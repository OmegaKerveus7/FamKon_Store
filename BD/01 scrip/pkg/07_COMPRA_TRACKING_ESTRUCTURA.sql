BEGIN
 IF INSERTING OR :OLD.ID_ESTADO_PAGO <> :NEW.ID_ESTADO_PAGO THEN
 INSERT INTO PAGO_ESTADO_HISTORIAL(ID_PAGO,ID_ESTADO_ANTERIOR,ID_ESTADO_NUEVO,ACTOR,COMENTARIO)
