-- ============================================================
--  MODULO DE PERSONALIZACION DE PRODUCTOS (SIN COSTO EXTRA)
--  - Propietario y producto de cada personalizacion
--  - Contenido por lado A/B: imagen, mensaje o configuracion JSON
--  - Paquete PKG_PERSONALIZACION (crear / actualizar / obtener)
-- ============================================================

SET DEFINE OFF
SET SERVEROUTPUT ON

DECLARE
    V_COUNT NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_COUNT
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'PERSONALIZACION' AND COLUMN_NAME = 'ID_USUARIO';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PERSONALIZACION ADD (ID_USUARIO NUMBER(19))';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'PERSONALIZACION' AND COLUMN_NAME = 'ID_PRODUCTO';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PERSONALIZACION ADD (ID_PRODUCTO NUMBER(19))';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_PERSONA_USUARIO';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PERSONALIZACION ADD CONSTRAINT FK_PERSONA_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES USUARIO (ID_USUARIO)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'FK_PERSONA_PRODUCTO';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PERSONALIZACION ADD CONSTRAINT FK_PERSONA_PRODUCTO FOREIGN KEY (ID_PRODUCTO) REFERENCES PRODUCTO (ID_PRODUCTO)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'IX_PERSONA_USUARIO';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_PERSONA_USUARIO ON PERSONALIZACION (ID_USUARIO)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'IX_PERSONA_PRODUCTO';
    IF V_COUNT = 0 THEN
        EXECUTE IMMEDIATE 'CREATE INDEX IX_PERSONA_PRODUCTO ON PERSONALIZACION (ID_PRODUCTO)';
    END IF;

    SELECT COUNT(*) INTO V_COUNT
      FROM USER_CONSTRAINTS
     WHERE CONSTRAINT_NAME = 'CK_PERSONA_CONTENIDO';
    IF V_COUNT > 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PERSONALIZACION DROP CONSTRAINT CK_PERSONA_CONTENIDO';
    END IF;
    EXECUTE IMMEDIATE 'ALTER TABLE PERSONALIZACION ADD CONSTRAINT CK_PERSONA_CONTENIDO CHECK (
        ID_ARCHIVO_LADO_A IS NOT NULL OR ID_ARCHIVO_LADO_B IS NOT NULL OR
        MENSAJE_LADO_A IS NOT NULL OR MENSAJE_LADO_B IS NOT NULL OR
        CONFIG_LADO_A IS NOT NULL OR CONFIG_LADO_B IS NOT NULL
    )';
END;
/

-- Los productos NFC existentes permiten personalizar ambos lados.
UPDATE PRODUCTO
   SET PERMITE_LADO_A = 'S',
       PERMITE_LADO_B = 'S'
 WHERE UPPER(NOMBRE) LIKE '%NFC%'
    OR UPPER(SKU) LIKE '%NFC%';
COMMIT;

CREATE OR REPLACE PACKAGE PKG_PERSONALIZACION AS
    PROCEDURE SP_CREAR (
        P_ID_USUARIO IN PERSONALIZACION.ID_USUARIO%TYPE,
        P_ID_PRODUCTO IN PERSONALIZACION.ID_PRODUCTO%TYPE,
        P_ID_ARCHIVO_LADO_A IN PERSONALIZACION.ID_ARCHIVO_LADO_A%TYPE,
        P_ID_ARCHIVO_LADO_B IN PERSONALIZACION.ID_ARCHIVO_LADO_B%TYPE,
        P_MENSAJE_LADO_A IN PERSONALIZACION.MENSAJE_LADO_A%TYPE,
        P_MENSAJE_LADO_B IN PERSONALIZACION.MENSAJE_LADO_B%TYPE,
        P_CONFIG_LADO_A IN PERSONALIZACION.CONFIG_LADO_A%TYPE,
        P_CONFIG_LADO_B IN PERSONALIZACION.CONFIG_LADO_B%TYPE,
        O_ID_PERSONALIZACION OUT PERSONALIZACION.ID_PERSONALIZACION%TYPE
    );

    PROCEDURE SP_ACTUALIZAR (
        P_ID_PERSONALIZACION IN PERSONALIZACION.ID_PERSONALIZACION%TYPE,
        P_ID_USUARIO IN PERSONALIZACION.ID_USUARIO%TYPE,
        P_ID_ARCHIVO_LADO_A IN PERSONALIZACION.ID_ARCHIVO_LADO_A%TYPE,
        P_ID_ARCHIVO_LADO_B IN PERSONALIZACION.ID_ARCHIVO_LADO_B%TYPE,
        P_MENSAJE_LADO_A IN PERSONALIZACION.MENSAJE_LADO_A%TYPE,
        P_MENSAJE_LADO_B IN PERSONALIZACION.MENSAJE_LADO_B%TYPE,
        P_CONFIG_LADO_A IN PERSONALIZACION.CONFIG_LADO_A%TYPE,
        P_CONFIG_LADO_B IN PERSONALIZACION.CONFIG_LADO_B%TYPE
    );

    PROCEDURE SP_OBTENER (
        P_ID_PERSONALIZACION IN PERSONALIZACION.ID_PERSONALIZACION%TYPE,
        O_DATOS OUT SYS_REFCURSOR
    );
END PKG_PERSONALIZACION;
