CREATE OR REPLACE PACKAGE BODY PKG_PERSONALIZACION AS
    PROCEDURE VALIDAR_ARCHIVO (
        P_ID_ARCHIVO IN ARCHIVO.ID_ARCHIVO%TYPE,
        P_ID_USUARIO IN USUARIO.ID_USUARIO%TYPE,
        P_LADO IN CHAR
    ) AS
        V_COUNT NUMBER;
    BEGIN
        IF P_ID_ARCHIVO IS NULL THEN
            RETURN;
        END IF;

        SELECT COUNT(*) INTO V_COUNT
          FROM ARCHIVO
         WHERE ID_ARCHIVO = P_ID_ARCHIVO
           AND ID_USUARIO_CARGA = P_ID_USUARIO
           AND TIPO_ARCHIVO = 'DISENO_PERSONALIZACION'
           AND ACTIVO = 'S';

        IF V_COUNT = 0 THEN
            RAISE_APPLICATION_ERROR(-20422, 'La imagen del lado ' || P_LADO || ' no pertenece al usuario o no es un diseno valido.');
        END IF;
    END VALIDAR_ARCHIVO;

    PROCEDURE VALIDAR_PRODUCTO (
        P_ID_PRODUCTO IN PRODUCTO.ID_PRODUCTO%TYPE,
        P_HAY_LADO_A IN BOOLEAN,
        P_HAY_LADO_B IN BOOLEAN
    ) AS
        V_PERMITE_A PRODUCTO.PERMITE_LADO_A%TYPE;
        V_PERMITE_B PRODUCTO.PERMITE_LADO_B%TYPE;
    BEGIN
        SELECT PERMITE_LADO_A, PERMITE_LADO_B
          INTO V_PERMITE_A, V_PERMITE_B
          FROM PRODUCTO
         WHERE ID_PRODUCTO = P_ID_PRODUCTO
           AND ACTIVO = 'S';

        IF P_HAY_LADO_A AND V_PERMITE_A <> 'S' THEN
            RAISE_APPLICATION_ERROR(-20423, 'Este producto no permite personalizar el lado A.');
        END IF;
        IF P_HAY_LADO_B AND V_PERMITE_B <> 'S' THEN
            RAISE_APPLICATION_ERROR(-20424, 'Este producto no permite personalizar el lado B.');
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20421, 'El producto no existe o esta inactivo.');
    END VALIDAR_PRODUCTO;

    PROCEDURE SP_CREAR (
        P_ID_USUARIO IN PERSONALIZACION.ID_USUARIO%TYPE,
        P_ID_PRODUCTO IN PERSONALIZACION.ID_PRODUCTO%TYPE,
        P_ID_ARCHIVO_LADO_A IN PERSONALIZACION.ID_ARCHIVO_LADO_A%TYPE,
        P_ID_ARCHIVO_LADO_B IN PERSONALIZACION.ID_ARCHIVO_LADO_B%TYPE,
        P_MENSAJE_LADO_A IN PERSONALIZACION.MENSAJE_LADO_A%TYPE,
        P_MENSAJE_LADO_B IN PERSONALIZACION.MENSAJE_LADO_B%TYPE,
        P_CONFIG_LADO_A IN PERSONALIZACION.CONFIG_LADO_A%TYPE,
        P_CONFIG_LADO_B IN PERSONALIZACION.CONFIG_LADO_B%TYPE,
        O_ID_PERSONALIZACION OUT PERSONALIZACION.ID_PERSONALIZACION%TYPE
    ) AS
        V_MENSAJE_A PERSONALIZACION.MENSAJE_LADO_A%TYPE := NULLIF(TRIM(P_MENSAJE_LADO_A), '');
        V_MENSAJE_B PERSONALIZACION.MENSAJE_LADO_B%TYPE := NULLIF(TRIM(P_MENSAJE_LADO_B), '');
        V_HAY_A BOOLEAN;
        V_HAY_B BOOLEAN;
    BEGIN
        IF P_ID_USUARIO IS NULL OR P_ID_PRODUCTO IS NULL THEN
            RAISE_APPLICATION_ERROR(-20420, 'La personalizacion requiere usuario y producto.');
        END IF;

        V_HAY_A := P_ID_ARCHIVO_LADO_A IS NOT NULL OR V_MENSAJE_A IS NOT NULL OR P_CONFIG_LADO_A IS NOT NULL;
        V_HAY_B := P_ID_ARCHIVO_LADO_B IS NOT NULL OR V_MENSAJE_B IS NOT NULL OR P_CONFIG_LADO_B IS NOT NULL;

        IF NOT V_HAY_A AND NOT V_HAY_B THEN
            RAISE_APPLICATION_ERROR(-20425, 'Agrega una imagen, un mensaje o una configuracion.');
        END IF;

        VALIDAR_PRODUCTO(P_ID_PRODUCTO, V_HAY_A, V_HAY_B);
        VALIDAR_ARCHIVO(P_ID_ARCHIVO_LADO_A, P_ID_USUARIO, 'A');
        VALIDAR_ARCHIVO(P_ID_ARCHIVO_LADO_B, P_ID_USUARIO, 'B');

        INSERT INTO PERSONALIZACION (
            ID_USUARIO, ID_PRODUCTO, ID_ARCHIVO_LADO_A, ID_ARCHIVO_LADO_B,
            MENSAJE_LADO_A, MENSAJE_LADO_B, CONFIG_LADO_A, CONFIG_LADO_B
        ) VALUES (
            P_ID_USUARIO, P_ID_PRODUCTO, P_ID_ARCHIVO_LADO_A, P_ID_ARCHIVO_LADO_B,
            V_MENSAJE_A, V_MENSAJE_B, P_CONFIG_LADO_A, P_CONFIG_LADO_B
        ) RETURNING ID_PERSONALIZACION INTO O_ID_PERSONALIZACION;
    END SP_CREAR;

    PROCEDURE SP_ACTUALIZAR (
        P_ID_PERSONALIZACION IN PERSONALIZACION.ID_PERSONALIZACION%TYPE,
        P_ID_USUARIO IN PERSONALIZACION.ID_USUARIO%TYPE,
        P_ID_ARCHIVO_LADO_A IN PERSONALIZACION.ID_ARCHIVO_LADO_A%TYPE,
        P_ID_ARCHIVO_LADO_B IN PERSONALIZACION.ID_ARCHIVO_LADO_B%TYPE,
        P_MENSAJE_LADO_A IN PERSONALIZACION.MENSAJE_LADO_A%TYPE,
        P_MENSAJE_LADO_B IN PERSONALIZACION.MENSAJE_LADO_B%TYPE,
        P_CONFIG_LADO_A IN PERSONALIZACION.CONFIG_LADO_A%TYPE,
        P_CONFIG_LADO_B IN PERSONALIZACION.CONFIG_LADO_B%TYPE
    ) AS
        V_MENSAJE_A PERSONALIZACION.MENSAJE_LADO_A%TYPE := NULLIF(TRIM(P_MENSAJE_LADO_A), '');
        V_MENSAJE_B PERSONALIZACION.MENSAJE_LADO_B%TYPE := NULLIF(TRIM(P_MENSAJE_LADO_B), '');
        V_BLOQUEADA PERSONALIZACION.BLOQUEADA%TYPE;
        V_OWNER PERSONALIZACION.ID_USUARIO%TYPE;
        V_PRODUCTO PERSONALIZACION.ID_PRODUCTO%TYPE;
        V_HAY_A BOOLEAN;
        V_HAY_B BOOLEAN;
    BEGIN
        SELECT PR.BLOQUEADA, PR.ID_USUARIO, PR.ID_PRODUCTO
          INTO V_BLOQUEADA, V_OWNER, V_PRODUCTO
          FROM PERSONALIZACION PR
         WHERE PR.ID_PERSONALIZACION = P_ID_PERSONALIZACION
           FOR UPDATE;

        IF V_OWNER IS NULL OR V_OWNER <> P_ID_USUARIO THEN
            RAISE_APPLICATION_ERROR(-20426, 'Esta personalizacion no pertenece al usuario.');
        END IF;
        IF V_BLOQUEADA = 'S' THEN
            RAISE_APPLICATION_ERROR(-20427, 'La personalizacion ya fue usada en un pedido y no se puede editar.');
        END IF;

        V_HAY_A := P_ID_ARCHIVO_LADO_A IS NOT NULL OR V_MENSAJE_A IS NOT NULL OR P_CONFIG_LADO_A IS NOT NULL;
        V_HAY_B := P_ID_ARCHIVO_LADO_B IS NOT NULL OR V_MENSAJE_B IS NOT NULL OR P_CONFIG_LADO_B IS NOT NULL;

        IF NOT V_HAY_A AND NOT V_HAY_B THEN
            RAISE_APPLICATION_ERROR(-20425, 'Agrega una imagen, un mensaje o una configuracion.');
        END IF;

        VALIDAR_PRODUCTO(V_PRODUCTO, V_HAY_A, V_HAY_B);
        VALIDAR_ARCHIVO(P_ID_ARCHIVO_LADO_A, P_ID_USUARIO, 'A');
        VALIDAR_ARCHIVO(P_ID_ARCHIVO_LADO_B, P_ID_USUARIO, 'B');

        UPDATE PERSONALIZACION
           SET ID_ARCHIVO_LADO_A = P_ID_ARCHIVO_LADO_A,
               ID_ARCHIVO_LADO_B = P_ID_ARCHIVO_LADO_B,
               MENSAJE_LADO_A = V_MENSAJE_A,
               MENSAJE_LADO_B = V_MENSAJE_B,
               CONFIG_LADO_A = P_CONFIG_LADO_A,
               CONFIG_LADO_B = P_CONFIG_LADO_B
         WHERE ID_PERSONALIZACION = P_ID_PERSONALIZACION;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(-20428, 'La personalizacion no existe.');
    END SP_ACTUALIZAR;

    PROCEDURE SP_OBTENER (
        P_ID_PERSONALIZACION IN PERSONALIZACION.ID_PERSONALIZACION%TYPE,
        O_DATOS OUT SYS_REFCURSOR
    ) AS
    BEGIN
        OPEN O_DATOS FOR
            SELECT PR.ID_PERSONALIZACION, PR.ID_USUARIO, PR.ID_PRODUCTO,
                   PR.ID_ARCHIVO_LADO_A, PR.ID_ARCHIVO_LADO_B,
                   PR.MENSAJE_LADO_A, PR.MENSAJE_LADO_B,
                   PR.CONFIG_LADO_A, PR.CONFIG_LADO_B, PR.BLOQUEADA,
                   P.NOMBRE PRODUCTO, P.SKU SKU_PRODUCTO,
                   TO_CHAR(PR.FECHA_CREACION, 'YYYY-MM-DD"T"HH24:MI:SS.FF3TZH:TZM') FECHA_CREACION
              FROM PERSONALIZACION PR
              LEFT JOIN PRODUCTO P ON P.ID_PRODUCTO = PR.ID_PRODUCTO
             WHERE PR.ID_PERSONALIZACION = P_ID_PERSONALIZACION;
    END SP_OBTENER;
END PKG_PERSONALIZACION;
