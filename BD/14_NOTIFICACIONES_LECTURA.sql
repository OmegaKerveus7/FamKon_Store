CREATE TABLE NOTIFICACION_LECTURA (
 ID_USUARIO NUMBER(19) NOT NULL REFERENCES USUARIO(ID_USUARIO),
 ID_HISTORIAL NUMBER(19) NOT NULL REFERENCES PEDIDO_ESTADO_HISTORIAL(ID_HISTORIAL),
 FECHA_LECTURA TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT PK_NOTIFICACION_LECTURA PRIMARY KEY (ID_USUARIO, ID_HISTORIAL)
);
