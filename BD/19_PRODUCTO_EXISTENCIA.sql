-- Ejecutar como TIENDA_APP.
-- Existencias por producto + descuento automatico al vender y devolucion al cancelar.

ALTER TABLE PRODUCTO ADD (
    EXISTENCIA NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT CK_PRODUCTO_EXISTENCIA CHECK (EXISTENCIA >= 0)
);

COMMENT ON COLUMN PRODUCTO.EXISTENCIA IS 'Unidades disponibles. Se descuenta al crear el pedido y se devuelve al cancelarlo.';

-- Existencias iniciales reales.
UPDATE PRODUCTO SET EXISTENCIA = 15 WHERE SKU = 'TAR-NFC-01';
UPDATE PRODUCTO SET EXISTENCIA = 50 WHERE SKU = 'LLA-001';
UPDATE PRODUCTO SET EXISTENCIA = 0  WHERE SKU = 'ANI001';  -- anillo inactivo

-- Al insertar una linea de pedido: valida y descuenta.
CREATE OR REPLACE TRIGGER TRG_PEDIDO_DETALLE_STOCK
BEFORE INSERT ON PEDIDO_DETALLE
FOR EACH ROW
DECLARE
    V_EXISTENCIA NUMBER(10);
BEGIN
    SELECT EXISTENCIA INTO V_EXISTENCIA
      FROM PRODUCTO
     WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO
       FOR UPDATE;

    IF V_EXISTENCIA < :NEW.CANTIDAD THEN
        RAISE_APPLICATION_ERROR(-20709,
            'No hay existencias suficientes de ' || :NEW.NOMBRE_PRODUCTO ||
            ' (disponibles: ' || V_EXISTENCIA || ').');
    END IF;

    UPDATE PRODUCTO
       SET EXISTENCIA = EXISTENCIA - :NEW.CANTIDAD
     WHERE ID_PRODUCTO = :NEW.ID_PRODUCTO;
END;
/

-- Al cancelar un pedido: devuelve las unidades al inventario.
CREATE OR REPLACE TRIGGER TRG_PEDIDO_CANCELADO_STOCK
AFTER UPDATE OF ID_ESTADO_PEDIDO ON PEDIDO
FOR EACH ROW
WHEN (NEW.ID_ESTADO_PEDIDO <> OLD.ID_ESTADO_PEDIDO)
DECLARE
    V_CANCELADO NUMBER;
BEGIN
    SELECT COUNT(*) INTO V_CANCELADO
      FROM ESTADO_PEDIDO
     WHERE ID_ESTADO_PEDIDO = :NEW.ID_ESTADO_PEDIDO
       AND CODIGO = 'CANCELADO';

    IF V_CANCELADO > 0 THEN
        FOR D IN (SELECT ID_PRODUCTO, CANTIDAD
                    FROM PEDIDO_DETALLE
                   WHERE ID_PEDIDO = :NEW.ID_PEDIDO) LOOP
            UPDATE PRODUCTO
               SET EXISTENCIA = EXISTENCIA + D.CANTIDAD
             WHERE ID_PRODUCTO = D.ID_PRODUCTO;
        END LOOP;
    END IF;
END;
/

COMMIT;
