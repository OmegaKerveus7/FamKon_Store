-- Ejecutar como TIENDA_APP.
-- Limpieza de cuentas heredadas de la base compartida que quedaron sin sitio
-- (ID_SITIO nulo). No pueden iniciar sesion: PKG_SEGURIDAD.SP_OBTENER_AUTENTICACION
-- devuelve ID_SITIO y el login fallaba al leerlo. Ademas sus correos y nicknames
-- quedan ocupados e impiden volver a registrarse.
--
-- Ninguna de estas cuentas tiene pedidos, carritos, personalizaciones ni
-- credenciales: son cuentas sin historial de compras.

-- 1) Libera las fotos de credencial (FK USUARIO.ID_FOTO_ORIGINAL / ID_FOTO_MODIFICADA).
UPDATE USUARIO
   SET ID_FOTO_ORIGINAL = NULL,
       ID_FOTO_MODIFICADA = NULL
 WHERE ID_SITIO IS NULL;
/
-- 2) Registros dependientes sin cascada.
DELETE FROM BITACORA_ACCESO
 WHERE ID_USUARIO IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL);
/
DELETE FROM NOTIFICACION_LECTURA
 WHERE ID_USUARIO IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL);
/
DELETE FROM CREDENCIAL
 WHERE ID_USUARIO IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL);
/
DELETE FROM CREDENCIAL_ENVIO
 WHERE ID_USUARIO IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL);
/
DELETE FROM CARRITO
 WHERE ID_USUARIO IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL);
/
DELETE FROM PERSONALIZACION
 WHERE ID_USUARIO IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL);
/
-- 3) Fotos de registro: solo las que no usa un producto, una personalizacion
--    ni una evidencia de entrega.
DELETE FROM ARCHIVO
 WHERE ID_USUARIO_CARGA IN (SELECT ID_USUARIO FROM USUARIO WHERE ID_SITIO IS NULL)
   AND ID_ARCHIVO NOT IN (SELECT ID_ARCHIVO_IMAGEN FROM PRODUCTO WHERE ID_ARCHIVO_IMAGEN IS NOT NULL)
   AND ID_ARCHIVO NOT IN (SELECT ID_ARCHIVO_LADO_A FROM PERSONALIZACION WHERE ID_ARCHIVO_LADO_A IS NOT NULL)
   AND ID_ARCHIVO NOT IN (SELECT ID_ARCHIVO_LADO_B FROM PERSONALIZACION WHERE ID_ARCHIVO_LADO_B IS NOT NULL)
   AND ID_ARCHIVO NOT IN (SELECT ID_ARCHIVO_EVIDENCIA FROM ENTREGA WHERE ID_ARCHIVO_EVIDENCIA IS NOT NULL);
/
-- 4) Las cuentas sin sitio. USUARIO_ROL, TOKEN_RECUPERACION y
--    RECUPERACION_PASSWORD se borran en cascada.
DELETE FROM USUARIO
 WHERE ID_SITIO IS NULL
   AND NOT EXISTS (SELECT 1 FROM PEDIDO P WHERE P.ID_USUARIO = USUARIO.ID_USUARIO);
/
COMMIT;
